CREATE TABLE IF NOT EXISTS alert_event (
    id BIGINT PRIMARY KEY,
    fingerprint VARCHAR(128) NOT NULL,
    code VARCHAR(64) NOT NULL,
    severity VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    title VARCHAR(256) NOT NULL,
    message TEXT,
    details_json JSON,
    occurrences INT NOT NULL,
    first_triggered_at TIMESTAMP NOT NULL,
    last_triggered_at TIMESTAMP NOT NULL,
    acknowledged_at TIMESTAMP NULL,
    acknowledged_by BIGINT,
    resolved_at TIMESTAMP NULL,
    notification_status VARCHAR(32) NOT NULL,
    notification_attempts INT NOT NULL,
    last_notified_at TIMESTAMP NULL,
    next_notify_at TIMESTAMP NULL,
    notification_error TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_alert_event_status_updated (status, updated_at),
    INDEX idx_alert_event_fingerprint_status (fingerprint, status),
    INDEX idx_alert_event_next_notify (notification_status, next_notify_at)
);
